"""Numerical parity and missing-data safety of the deployed research estimator."""
import json
import math
import unittest
from unittest.mock import patch

import numpy as np

from app.ml.features import motion_windows
from app.services.fuel_prediction import MAX_TRIP_DURATION_S, predict_fuel


START = 1_760_000_000_000
PROFILE = {"fuel_type": "gasoline", "mass_kg": 1500, "displacement_l": 2., "turbo": True}


def samples(seconds=60, speed=10., start=START):
    return [{"timestamp_ms": start + t * 1000, "speed_mps": speed,
             "latitude": 55., "longitude": 37., "accuracy_m": 8., "speed_source": "gps"}
            for t in range(seconds + 1)]


class FuelPredictionTests(unittest.TestCase):
    def test_saved_model_parity_with_original_experiment(self):
        # Golden totals generated by ml_experiment/predict_trip.py, without this
        # service, from the saved 2026-10-18 artifacts and the speed profile below.
        trace = samples(65)
        for t, sample in enumerate(trace):
            sample["speed_mps"] = t * .4 if t <= 30 else 12. if t <= 35 else 12 - (t - 35) * .2
        result = predict_fuel(trace, PROFILE, START, START + 65_000)
        expected = {"physics": .047030815245743866, "catboost": .0507149411241124,
                    "hybrid": .045101829846272055}
        self.assertEqual(result["status"], "research_estimate")
        self.assertEqual(result["accepted_windows"], 3)
        self.assertAlmostEqual(result["distance_km"], .510)
        self.assertEqual(result["coverage_fraction"], 1.)
        for name, fuel in expected.items():
            self.assertAlmostEqual(result["fuel_l_on_retained_intervals"][name], fuel, places=12)
        self.assertEqual(result["complete_trip_fuel_l"], result["estimated_fuel_l"])
        json.dumps(result, allow_nan=False)

    def test_stopped_engine_is_not_zero_fuel(self):
        result = predict_fuel(samples(speed=0.), PROFILE, START, START + 60_000)
        self.assertEqual(result["retained_duration_s"], 60)
        self.assertEqual(result["distance_km"], 0.)
        self.assertAlmostEqual(result["fuel_l_on_retained_intervals"]["physics"],
                               1.5140490497934231 / 60, places=12)
        self.assertGreater(result["estimated_fuel_l"], 0.)

    def test_missing_gps_is_not_stationary_and_does_not_fill_session(self):
        trace = samples()
        for sample in trace[10:20]:
            sample["speed_mps"] = None
        result = predict_fuel(trace, PROFILE, START - 10_000, START + 70_000)
        self.assertEqual(result["session_duration_s"], 80.)
        self.assertEqual(result["retained_duration_s"], 30.)
        self.assertEqual(result["coverage_fraction"], 30 / 80)
        self.assertIsNone(result["complete_trip_fuel_l"])
        self.assertIn("missing_or_invalid_speed", result["quality_flags"])

    def test_long_gaps_are_not_interpolated_into_usable_windows(self):
        trace = samples(90)
        trace = trace[:11] + trace[31:]
        result = predict_fuel(trace, PROFILE, START, START + 90_000)
        self.assertEqual(result["retained_duration_s"], 30.)
        self.assertIn("gps_gap_over_10_seconds", result["quality_flags"])
        self.assertIsNone(result["complete_trip_fuel_l"])

    def test_missing_or_low_accuracy_invalidates_intervals(self):
        for accuracy in (None, 51., -1., math.nan):
            with self.subTest(accuracy=accuracy):
                trace = samples()
                trace[10]["accuracy_m"] = accuracy
                result = predict_fuel(trace, PROFILE, START, START + 60_000)
                self.assertEqual(result["retained_duration_s"], 30.)
                self.assertEqual(result["gps_accuracy_threshold_m"], 50.)

    def test_all_missing_returns_null_not_zero(self):
        result = predict_fuel(samples(speed=None), PROFILE, START, START + 60_000)
        self.assertEqual(result["status"], "no_usable_gps")
        self.assertIsNone(result["estimated_fuel_l"])
        self.assertTrue(all(value is None for value in result["fuel_l_on_retained_intervals"].values()))
        json.dumps(result, allow_nan=False)

    def test_missing_source_cannot_be_converted_to_false_stop(self):
        trace = samples(speed=0.)
        for point in trace:
            point["speed_source"] = "missing"
        result = predict_fuel(trace, PROFILE, START, START + 60_000)
        self.assertEqual(result["status"], "no_usable_gps")
        self.assertIsNone(result["estimated_fuel_l"])
        self.assertIn("unknown_speed_source", result["quality_flags"])

    def test_sub_five_second_tail_is_not_scaled_up(self):
        result = predict_fuel(samples(34), PROFILE, START, START + 34_000)
        self.assertEqual(result["retained_duration_s"], 30.)
        self.assertEqual(result["unestimated_duration_s"], 4.)
        self.assertIsNone(result["complete_trip_fuel_l"])

    def test_unrealistic_acceleration_rejects_affected_window(self):
        trace = samples()
        trace[10]["speed_mps"] = 30.
        result = predict_fuel(trace, PROFILE, START, START + 60_000)
        self.assertEqual(result["status"], "research_estimate")
        self.assertEqual(result["retained_duration_s"], 30.)
        self.assertEqual(result["rejected_windows"], 1)

    def test_outside_session_points_do_not_extend_coverage(self):
        trace = samples(80, start=START - 10_000)
        result = predict_fuel(trace, PROFILE, START, START + 60_000)
        self.assertEqual(result["retained_duration_s"], 60.)
        self.assertEqual(result["gps_sample_counts"]["outside_session"], 20)
        self.assertEqual(result["coverage_fraction"], 1.)

    def test_duration_bound_prevents_huge_resampling(self):
        with patch("app.services.fuel_prediction.motion_windows") as extraction:
            result = predict_fuel(samples(1), PROFILE, START,
                                  START + (MAX_TRIP_DURATION_S + 1) * 1000)
        self.assertEqual(result["status"], "invalid_trip")
        extraction.assert_not_called()

    def test_profile_requires_confirmed_gasoline_and_turbo(self):
        for fuel, expected in (("diesel", "unsupported_vehicle"), ("unknown", "profile_incomplete")):
            result = predict_fuel(samples(), {**PROFILE, "fuel_type": fuel}, START, START + 60_000)
            self.assertEqual(result["status"], expected)
            self.assertIsNone(result["estimated_fuel_l"])
        result = predict_fuel(samples(), {**PROFILE, "turbo": None}, START, START + 60_000)
        self.assertEqual(result["missing_profile_fields"], ["turbo"])

    def test_conflicting_duplicates_are_order_independent(self):
        trace = samples()
        conflicting = {**trace[10], "speed_mps": 20.}
        one = predict_fuel(trace + [conflicting], PROFILE, START, START + 60_000)
        two = predict_fuel([conflicting] + list(reversed(trace)), PROFILE, START, START + 60_000)
        self.assertEqual(one, two)
        self.assertEqual(one["retained_duration_s"], 30.)

    def test_missing_model_does_not_break_trip_collection(self):
        with patch("app.services.fuel_prediction._load_artifacts", side_effect=FileNotFoundError("test")):
            result = predict_fuel(samples(), PROFILE, START, START + 60_000)
        self.assertEqual(result["status"], "model_unavailable")
        self.assertIsNone(result["estimated_fuel_l"])
        self.assertEqual(result["retained_duration_s"], 60.)

    def test_out_of_training_range_is_visible(self):
        result = predict_fuel(samples(), {**PROFILE, "mass_kg": 4000}, START, START + 60_000)
        self.assertEqual(result["status"], "research_estimate")
        self.assertIn("mass_kg", result["features_outside_training_range"])
        self.assertIn("outside_training_range", result["quality_flags"])

    def test_irregular_timestamps_integrate_distance_not_sample_count(self):
        # Four unequal intervals total 30s; a constant 10m/s covers exactly 300m.
        profile = {"mass_kg": 1500., "displacement_l": 2., "turbo_tag": 1.}
        rows, _, good = motion_windows([0., 3., 10., 20., 30.], np.full(5, 10.), profile)
        self.assertTrue(good.all())
        self.assertAlmostEqual(rows[0]["distance_m"], 300.)

    def test_no_obd_label_or_identity_leak_into_predictions(self):
        clean = samples()
        decorated = [{**point, "MAF[g/sec]": 9000, "Fuel Rate[L/hr]": 200,
                      "VehId": 12, "engine_rpm": 1000} for point in clean]
        first = predict_fuel(clean, PROFILE, START, START + 60_000)
        second = predict_fuel(decorated, PROFILE, START, START + 60_000)
        self.assertEqual(first, second)


if __name__ == "__main__":
    unittest.main()
