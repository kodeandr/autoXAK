def validate_fleet_seed_data(fleet_data: list[dict[str, Any]]) -> None:
    """Явный валидатор целостности каталога (не зависит от флага Python -O)."""
    if len(fleet_data) != 128:
        raise ValueError(f"Expected 128 vehicle profiles, got {len(fleet_data)}")

    ids = [profile["id"] for profile in fleet_data]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate profile IDs detected in FLEET_SEED_DATA")

    identity_keys = [
        (
            profile["make"],
            profile["model"],
            profile["generation"],
            profile["trim_name"],
        )
        for profile in fleet_data
    ]
    if len(identity_keys) != len(set(identity_keys)):
        raise ValueError("Duplicate natural keys (make, model, generation, trim_name) detected")

    if not PERMANENT_4WD_WITH_TRANSFER_CASE_IDS <= set(ids):
        raise ValueError("Missing expected permanent 4WD IDs")
    if not HIGH_PROFILE_TIRE_PRIOR_IDS <= set(ids):
        raise ValueError("Missing expected high-profile tire prior IDs")

    model_body_map: dict[tuple[str, str], str] = {}

    for profile in fleet_data:
        if not REQUIRED_FIELDS <= profile.keys():
            missing = REQUIRED_FIELDS - profile.keys()
            raise ValueError(f"Profile {profile.get('id')} missing fields: {missing}")

        if any(value is None for value in profile.values()):
            raise ValueError(f"Profile {profile['id']} contains None values")

        for field in POSITIVE_NUMERIC_FIELDS:
            value = profile[field]
            if not isinstance(value, (int, float)) or isinstance(value, bool):
                raise TypeError(f"Field {field} in {profile['id']} must be numeric")
            if not isfinite(value) or value <= 0:
                raise ValueError(f"Field {field} in {profile['id']} must be finite and > 0")

        for field in REQUIRED_FIELDS - set(POSITIVE_NUMERIC_FIELDS):
            value = profile[field]
            if not isinstance(value, str) or not value.strip():
                raise ValueError(f"Field {field} in {profile['id']} must be a non-empty string")

        if profile["make"] not in MAKE_COUNTRIES:
            raise ValueError(f"Unknown make country mapping for {profile['make']}")

        if profile["drive_type"] not in {"FWD", "AWD", "4WD"}:
            raise ValueError(f"Invalid drive_type in {profile['id']}: {profile['drive_type']}")

        if profile["transmission_type"] not in {"MT", "AT", "CVT", "DCT"}:
            raise ValueError(
                f"Invalid transmission_type in {profile['id']}: {profile['transmission_type']}"
            )

        if profile["body_type"] not in {
            "sedan",
            "hatchback",
            "liftback",
            "wagon",
            "crossover",
            "suv",
        }:
            raise ValueError(f"Invalid body_type in {profile['id']}: {profile['body_type']}")

        model_key = (profile["make"], profile["model"])
        if model_key in model_body_map and model_body_map[model_key] != profile["body_type"]:
            raise ValueError(f"Inconsistent body_type for {model_key}")
        model_body_map[model_key] = profile["body_type"]

        expected_cd_a = round(profile["drag_coefficient"] * profile["frontal_area_m2"], 3)
        if profile["cd_a"] != expected_cd_a:
            raise ValueError(
                f"cd_a mismatch in {profile['id']}: {profile['cd_a']} != {expected_cd_a}"
            )

        if profile["id"] in PERMANENT_4WD_WITH_TRANSFER_CASE_IDS:
            if profile["drive_type"] != "4WD":
                raise ValueError(f"Expected 4WD for {profile['id']}")
            expected_efficiency = 0.82
        elif profile["drive_type"] in {"AWD", "4WD"}:
            expected_efficiency = 0.87
        elif profile["transmission_type"] in {"MT", "DCT"}:
            expected_efficiency = 0.91
        else:
            expected_efficiency = 0.89

        expected_rolling_res = (
            0.015 if profile["id"] in HIGH_PROFILE_TIRE_PRIOR_IDS else 0.013
        )

        if profile["transmission_efficiency"] != expected_efficiency:
            raise ValueError(
                f"Efficiency mismatch in {profile['id']}: "
                f"{profile['transmission_efficiency']} != {expected_efficiency}"
            )
        if profile["rolling_res_coeff"] != expected_rolling_res:
            raise ValueError(
                f"Rolling resistance mismatch in {profile['id']}: "
                f"{profile['rolling_res_coeff']} != {expected_rolling_res}"
            )
        if profile["param_source"] != "oem_spec_and_class_prior":
            raise ValueError(f"Unexpected param_source in {profile['id']}")


# Выполняем проверку целостности при импорте модуля
validate_fleet_seed_data(ALL_FLEET_SEED_DATA)


def _slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    return slug[:95]


async def upsert_fleet_from_flat_list(
    session: Any,
    fleet_data: list[dict[str, Any]] | None = None,
) -> int:
    """
    Загружает или обновляет (upsert) 128 модификаций в реляционные таблицы
    vehicle_makes -> vehicle_models -> vehicle_trims.
    Автоматически адаптируется под набор колонок VehicleTrim в текущей схеме БД.
    """
    from app.models.db_models import VehicleMake, VehicleModel, VehicleTrim

    data = fleet_data if fleet_data is not None else ALL_FLEET_SEED_DATA
    validate_fleet_seed_data(data)

    trim_columns = {col.name for col in VehicleTrim.__table__.columns}
    count = 0

    for item in data:
        make_id = _slugify(item["make"])
        model_id = _slugify(f"{item['make']}_{item['model']}")
        trim_id = item["id"]

        # 1. VehicleMake
        make_obj = await session.get(VehicleMake, make_id)
        if not make_obj:
            make_obj = VehicleMake(
                id=make_id,
                name=item["make"],
                country=MAKE_COUNTRIES.get(item["make"], "INT"),
            )
            session.add(make_obj)
            await session.flush()
        else:
            make_obj.name = item["make"]
            make_obj.country = MAKE_COUNTRIES.get(item["make"], "INT")

        # 2. VehicleModel
        model_obj = await session.get(VehicleModel, model_id)
        if not model_obj:
            model_obj = VehicleModel(
                id=model_id,
                make_id=make_id,
                name=item["model"],
                body_type=item["body_type"],
            )
            session.add(model_obj)
            await session.flush()
        else:
            model_obj.make_id = make_id
            model_obj.name = item["model"]
            model_obj.body_type = item["body_type"]

        # 3. VehicleTrim
        badge_name = f"{item['trim_name']} ({item['generation']})"[:120]
        rated_power_kw = round(float(item["power_hp"]) * 0.73549875, 1)

        trim_values: dict[str, Any] = {
            "model_id": model_id,
            "badge_name": badge_name,
            "curb_weight_kg": float(item["curb_weight_kg"]),
            "drag_coefficient_area": float(item["cd_a"]),
            "rolling_resistance_coeff": float(item["rolling_res_coeff"]),
            "drivetrain_efficiency": float(item["transmission_efficiency"]),
            "engine_displacement_l": float(item["engine_displacement_l"]),
            "rated_power_kw": rated_power_kw,
            "drivetrain_type": item["drive_type"],
            "transmission_type": item["transmission_type"],
            "oil_capacity_l": float(item["oil_capacity_l"]),
            "oil_grade": item["oil_grade"],
            "oil_spec": item["oil_spec"],
            # Опциональные/расширенные поля схемы, если они присутствуют в модели БД:
            "base_city_fuel_rate_l100km": float(item["base_city_fuel_rate_l100km"]),
            "city_fuel_rate_l100km": float(item["base_city_fuel_rate_l100km"]),
            "passport_fuel_l100km": float(item["base_city_fuel_rate_l100km"]),
            "fuel_rate_source": item["param_source"],
            "param_source": item["param_source"],
            "recommended_fuel": item["recommended_fuel"],
            "generation": item["generation"],
            "trim_name": item["trim_name"],
            "engine_type": item["engine_type"],
            "power_hp": int(item["power_hp"]),
            "drag_coefficient": float(item["drag_coefficient"]),
            "frontal_area_m2": float(item["frontal_area_m2"]),
        }

        filtered_values = {
            k: v for k, v in trim_values.items() if k in trim_columns
        }

        trim_obj = await session.get(VehicleTrim, trim_id)
        if not trim_obj:
            trim_obj = VehicleTrim(id=trim_id, **filtered_values)
            session.add(trim_obj)
        else:
            for k, v in filtered_values.items():
                setattr(trim_obj, k, v)

        count += 1

    await session.commit()
    return count


async def seed_fleet(session: Any | None = None) -> int:
    """Точка входа для CLI и автотестов."""
    if session is not None:
        return await upsert_fleet_from_flat_list(session, ALL_FLEET_SEED_DATA)

    from app.core.database import async_session_factory as AsyncSessionLocal, initialize_schema as init_db

    await init_db()
    async with AsyncSessionLocal() as db_session:
        inserted = await upsert_fleet_from_flat_list(db_session, ALL_FLEET_SEED_DATA)
        print(
            f"[OK] seed_fleet.py: успешно синхронизировано {inserted} модификаций "
            f"({len(MAKE_COUNTRIES)} марок)."
        )
        return inserted


if __name__ == "__main__":
    asyncio.run(seed_fleet())
